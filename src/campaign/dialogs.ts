/** Сцена повода, если её ещё не показывали */
export function sceneFor(trigger: string, seen: string[]): Scene | null {
  const id = SCENE_AT[trigger];
  if (!id || seen.includes(id)) return null;
  return SCENES.find((s) => s.id === id) ?? null;
}
